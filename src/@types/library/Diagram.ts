import { z } from 'zod'
import { DIAGRAM_COMPONENT_CODE } from './DiagramComponent'

/*
 * A reference architecture's drag-and-drop diagram (library_assets.diagram). A diagram has views
 * (scenarios such as "GL planning only" / "Advanced FP&A planning"); each view has components (nodes),
 * labelled connections (edges) and notes. A node's `kind` is a component type's code. Components can
 * carry a build step and build guidance (Markdown). The server validates the whole document with
 * DiagramSchema before storing it.
 */

/**
 * A node's component type: the code of a diagram_components row (DiagramComponent.ts). Types are data
 * (editors manage them), so any well-formed code is accepted; an unknown one shows the fallback look.
 */
export type DiagramNodeKind = string

export const DIAGRAM_NOTE_TONES = ['info', 'warning'] as const
export type DiagramNoteTone = (typeof DIAGRAM_NOTE_TONES)[number]

export const DIAGRAM_LIMITS = {
    views: 12,
    nodes: 150,
    edges: 300,
    notes: 10,
    viewName: 80,
    viewDescription: 300,
    nodeLabel: 80,
    nodeSubtitle: 80,
    guidance: 5000,
    edgeLabel: 60,
    note: 500,
    maxStep: 99,
    coordinate: 100000,
    /** The whole document as JSON, in characters (keeps saves well under the request size limit) */
    json: 1_000_000,
} as const

/** Element ids inside a diagram (generated by the editor: letters, digits, '-' and '_') */
const DiagramIdSchema = z
    .string()
    .min(1)
    .max(64)
    .regex(/^[A-Za-z0-9_-]+$/, 'Use letters, digits, - and _ in ids')

const clampCoordinate = (value: number) =>
    Math.max(-DIAGRAM_LIMITS.coordinate, Math.min(DIAGRAM_LIMITS.coordinate, value))

const CoordinateSchema = z.number().finite().transform(clampCoordinate)

export const DiagramNodeSchema = z.object({
    id: DiagramIdSchema,
    kind: z.string().regex(DIAGRAM_COMPONENT_CODE, 'Choose a component type'),
    label: z.string().trim().min(1, 'Give the component a name').max(DIAGRAM_LIMITS.nodeLabel),
    subtitle: z.string().trim().max(DIAGRAM_LIMITS.nodeSubtitle).default(''),
    x: CoordinateSchema,
    y: CoordinateSchema,
    step: z.number().int().min(1).max(DIAGRAM_LIMITS.maxStep).nullable().default(null),
    guidance: z.string().max(DIAGRAM_LIMITS.guidance, 'Keep the build guidance under 5,000 characters').default(''),
})
export type DiagramNode = z.infer<typeof DiagramNodeSchema>

export const DiagramEdgeSchema = z.object({
    id: DiagramIdSchema,
    source: DiagramIdSchema,
    target: DiagramIdSchema,
    label: z.string().trim().max(DIAGRAM_LIMITS.edgeLabel).default(''),
})
export type DiagramEdge = z.infer<typeof DiagramEdgeSchema>

export const DiagramNoteSchema = z.object({
    id: DiagramIdSchema,
    tone: z.enum(DIAGRAM_NOTE_TONES).default('info'),
    text: z.string().trim().max(DIAGRAM_LIMITS.note, 'Keep notes under 500 characters'),
})
export type DiagramNote = z.infer<typeof DiagramNoteSchema>

export const DiagramViewSchema = z
    .object({
        id: DiagramIdSchema,
        name: z.string().trim().min(1, 'Give the view a name').max(DIAGRAM_LIMITS.viewName),
        description: z.string().trim().max(DIAGRAM_LIMITS.viewDescription).default(''),
        nodes: z.array(DiagramNodeSchema).max(DIAGRAM_LIMITS.nodes, 'Use up to 150 components per view').default([]),
        edges: z.array(DiagramEdgeSchema).max(DIAGRAM_LIMITS.edges, 'Use up to 300 connections per view').default([]),
        notes: z.array(DiagramNoteSchema).max(DIAGRAM_LIMITS.notes, 'Use up to 10 notes per view').default([]),
    })
    .superRefine((view, ctx) => {
        const nodeIds = new Set<string>()
        view.nodes.forEach((node, i) => {
            if (nodeIds.has(node.id)) {
                ctx.addIssue({ code: 'custom', path: ['nodes', i, 'id'], message: 'Duplicate component id' })
            }
            nodeIds.add(node.id)
        })
        const edgeIds = new Set<string>()
        view.edges.forEach((edge, i) => {
            if (edgeIds.has(edge.id)) {
                ctx.addIssue({ code: 'custom', path: ['edges', i, 'id'], message: 'Duplicate connection id' })
            }
            edgeIds.add(edge.id)
            if (!nodeIds.has(edge.source) || !nodeIds.has(edge.target)) {
                ctx.addIssue({
                    code: 'custom',
                    path: ['edges', i],
                    message: 'A connection points to a component that isn’t in the view',
                })
            }
        })
        const noteIds = new Set<string>()
        view.notes.forEach((note, i) => {
            if (noteIds.has(note.id)) {
                ctx.addIssue({ code: 'custom', path: ['notes', i, 'id'], message: 'Duplicate note id' })
            }
            noteIds.add(note.id)
        })
    })
export type DiagramView = z.infer<typeof DiagramViewSchema>

export const DiagramSchema = z
    .object({
        views: z.array(DiagramViewSchema).max(DIAGRAM_LIMITS.views, 'Use up to 12 views').default([]),
    })
    .superRefine((diagram, ctx) => {
        const ids = new Set<string>()
        diagram.views.forEach((view, i) => {
            if (ids.has(view.id))
                ctx.addIssue({ code: 'custom', path: ['views', i, 'id'], message: 'Duplicate view id' })
            ids.add(view.id)
        })
        if (JSON.stringify(diagram).length > DIAGRAM_LIMITS.json) {
            ctx.addIssue({
                code: 'custom',
                path: ['views'],
                message: 'The diagram is too large. Split it into fewer views or shorten the build guidance.',
            })
        }
    })
export type Diagram = z.infer<typeof DiagramSchema>

/** A diagram with no views (what a new asset starts with) */
export const emptyDiagram = (): Diagram => ({ views: [] })

/** A stored diagram (jsonb); anything that doesn't validate reads as an empty diagram */
export function parseDiagram(json: unknown): Diagram {
    const parsed = DiagramSchema.safeParse(json)
    return parsed.success ? parsed.data : emptyDiagram()
}

/** "2 views · 14 components" on library cards */
export interface DiagramSummary {
    views: number
    components: number
}
